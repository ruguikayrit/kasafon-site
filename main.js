const prices = {
  plus: { monthly: "99 TL", yearly: "990 TL" },
  pro: { monthly: "169 TL", yearly: "1.690 TL" }
};

const page = document.documentElement;
let lang = localStorage.getItem("kasafon-site-lang") === "en" ? "en" : "tr";
let billing = "yearly";

function applyLang() {
  const dict = copy[lang];
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (dict[key] != null) node.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.getAttribute("data-i18n-aria");
    if (dict[key] != null) node.setAttribute("aria-label", dict[key]);
  });
  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", button.getAttribute("data-set-lang") === lang ? "true" : "false");
  });
  page.lang = lang;
  document.title = dict["meta.title"];
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute("content", dict["meta.description"]);
  applyBilling();
}

function applyBilling() {
  const dict = copy[lang];
  document.querySelectorAll("[data-billing]").forEach((button) => {
    button.setAttribute("aria-pressed", button.getAttribute("data-billing") === billing ? "true" : "false");
  });
  document.querySelectorAll("[data-price]").forEach((node) => {
    const plan = node.getAttribute("data-price");
    node.textContent = prices[plan][billing];
  });
  document.querySelectorAll("[data-period]").forEach((node) => {
    node.textContent = billing === "yearly" ? dict["plans.perYear"] : dict["plans.perMonth"];
  });
  const note = document.querySelector(".billing-note");
  if (note) note.textContent = billing === "yearly" ? dict["plans.yearlyNote"] : dict["plans.monthlyNote"];
}

document.querySelectorAll("[data-set-lang]").forEach((button) => {
  button.addEventListener("click", () => {
    lang = button.getAttribute("data-set-lang");
    localStorage.setItem("kasafon-site-lang", lang);
    applyLang();
  });
});

document.querySelectorAll("[data-billing]").forEach((button) => {
  button.addEventListener("click", () => {
    billing = button.getAttribute("data-billing");
    applyBilling();
  });
});

applyLang();
